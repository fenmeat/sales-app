import test from 'node:test';
import assert from 'node:assert/strict';
import {fixture} from './helpers/report-fixture.js';
import {savePaReport,readPaReport} from '../src/pa-report-api.js';
import {projectMail,readMail} from '../src/pa-email.js';
import {today} from '../src/domain.js';

test('PA email follows an immutable approval, Gmail evidence and the existing task through Tasks and Daily Report',async t=>{
 const {db,call}=await fixture(t);
 const env={DB:db,APP_ACCESS_KEYS:JSON.stringify({alex:'a'.repeat(40),alinda:'b'.repeat(40)})};
 const pa={username:'alex',via:'pa'},source='https://docs.google.com/spreadsheets/d/synthetic/edit';
 const rows=['TSK-00001','TSK-00002','TSK-00003'].map(id=>({id,title:'Private follow-up',area:'Legal',scope:'private',status:'Waiting',assigned_to:'alex',source_url:source,review_date:today(),next_action:'Read court reply.'}));
 const publish=(operation,data,revision=0)=>savePaReport(env,pa,{operation,data,revision,request_id:crypto.randomUUID(),reason:'Synthetic authorised test'});
 await publish('register',{source_at:new Date().toISOString(),source_url:source,rows});
 const future='2099-01-05',thread_id='aa11223344',parent_id='bead1234',key=rows[0].id;
 const draft={envelope:{from:'owner@example.com',to:['office@example.com'],subject:'Update',body:'Please confirm the current status.',scope:'Request status',thread_id,parent_id},review_date:future,next_action:'PA kyk vir die antwoord.'};
 const cmd=(id,action,revision,data={},request_id=crypto.randomUUID())=>({operation:'email_followup',subject_key:id,action,revision,data,request_id,reason:'Synthetic verified instruction'});
 const write=(...args)=>savePaReport(env,pa,cmd(...args));
 const read=()=>readMail(db,key);
 const submit=async(id,d)=>{await write(id,'draft',0,d);await write(id,'submit',1);return readMail(db,id);};
 const approve=async(id,revision,envelope_hash)=>{const b=cmd(id,'approve',revision,{envelope_hash});return call('alex','/api/pa-report/email',b);};
 const m=await submit(key,draft),digest=m.envelope_hash;
 assert.equal((await call('alinda','/api/pa-report/email?subject_key='+key)).status,403);
 await assert.rejects(write(key,'claim',2,{envelope_hash:digest}),/goedkeuring/);
 await assert.rejects(write(key,'approve',2,{envelope_hash:digest}),/beskikbaar/);
 assert.equal((await approve(key,2,'different')).status,409);
 assert.equal((await approve(key,2,digest)).status,200);
 assert.equal((await read()).phase,'approved');assert.equal((await read()).message_id,undefined);
 const claims=await Promise.allSettled([write(key,'claim',3,{envelope_hash:digest}),write(key,'claim',3,{envelope_hash:digest})]);
 assert.equal(claims.filter(x=>x.status==='fulfilled').length,1);
 await write(key,'failed',4);
 await assert.rejects(write(key,'claim',5,{envelope_hash:digest}),/goedkeuring/);
 const evidence={message_id:'ab001122',rfc_id:'<m1@example.com>',thread_id,labels:['SENT'],sent_at:new Date(Date.now()-10000).toISOString(),envelope_hash:digest};
 await assert.rejects(write(key,'sent',5,{evidence:{...evidence,labels:['DRAFT']}}),/Gmail/);
 const sentData={evidence,review_date:future,next_action:'Kontroleer die hofstatus.'},retry=crypto.randomUUID();
 await write(key,'sent',5,sentData,retry);
 assert.equal((await write(key,'sent',5,sentData,retry)).replayed,true);
 const lookup=(id)=>readPaReport(env,pa,{resource:'summary',id});
 const task=(await lookup(key)).subject;
 assert.equal(task.status,'Scheduled');assert.equal(task.email.message_id,evidence.message_id);
 const workspace=await call('alex','/api/tasks/workspace?scope=private&status=scheduled');assert.equal(workspace.data.pa.workspace.rows[0].email.label,task.email.label);
 const ctx=await lookup('report-context');assert.deepEqual(ctx.followup.find(r=>r.id===key).email,task.email);
 assert.equal(projectMail(rows[0],task.email,future).email.phase,'due');assert.equal(projectMail(rows[0],task.email,future).status,'Pending');
 const sections=['emails','activity','tasks','tomorrow','rabbi'].map(id=>({id,title:id,items:[{id,text:task.email.label,title:'Synthetic',pa_task_ids:id==='tasks'?[key]:[]}]}));
 await publish('report',{date:today(),source_at:new Date().toISOString(),source_url:source,register_revision:1,sections});
 const published=(await readPaReport(env,pa)).report.sections[2].items[0];
 assert.equal(published.text,task.email.label);assert.equal(published.email_updates[0].sent_at,evidence.sent_at);
 const before=await db.prepare('SELECT count(*) n FROM v2_pa_followup_mail').first();
 await write(key,'checked',6,{checked_at:new Date().toISOString(),check_after:new Date(Date.now()+3600000).toISOString()});
 assert.ok(!(await lookup('email-work')).items.some(x=>x.id===key));
 assert.deepEqual(await db.prepare('SELECT count(*) n FROM v2_pa_followup_mail').first(),before);
 const second=rows[1].id;await submit(second,draft);await approve(second,2,digest);
 await assert.rejects(write(second,'claim',3,{envelope_hash:digest}),/reeds/);
 const changed={...draft,envelope:{...draft.envelope,body:'A different question.'}};
 await write(second,'draft',3,changed);await assert.rejects(write(second,'claim',4,{envelope_hash:digest}),/goedkeuring/);
 const reply={from:'office@example.com',message_id:'ab112244',in_reply_to:evidence.rfc_id,thread_id,received_at:new Date().toISOString()};
 await assert.rejects(write(key,'reply',6,{evidence:{...reply,in_reply_to:'<other@x>'},review_date:today(),next_action:'Read reply.'}),/spesifieke/);
 await write(key,'reply',6,{evidence:reply,review_date:today(),next_action:'Lees dokumente en bevestig uitkoms.'});
 assert.equal((await lookup(key)).subject.email.phase,'reply');assert.equal((await lookup(key)).subject.status,'Pending');
 await publish('register_patch',{source_at:new Date().toISOString(),source_url:source,rows:[{...rows[0],status:'Complete'}]},1);
 assert.equal((await lookup(key)).subject.email.phase,'completed');
 assert.equal((await lookup('report-context')).followup.find(r=>r.id===key).category,'completed');
 assert.equal((await lookup('email-work')).items.some(x=>x.id===key),false);
 assert.equal((await lookup(rows[2].id)).subject.next_action,rows[2].next_action);
});

test('a direct human reply can reuse only its exact reviewed draft and reply attribution survives shared threads',async t=>{
 const {db,call}=await fixture(t),user={username:'alex',via:'pa'};
 const env={DB:db,APP_ACCESS_KEYS:JSON.stringify({alex:'a'.repeat(40)})},url='https://docs.google.com/spreadsheets/d/example/edit';
 const ids=['TSK-00004','TSK-00005'],rows=ids.map(id=>({id,title:'Follow-up',area:'Legal',scope:'private',assigned_to:'alex',status:'Waiting',review_date:today(),source_url:url}));
 await savePaReport(env,user,{operation:'register',revision:0,data:{source_at:new Date().toISOString(),source_url:url,rows},request_id:crypto.randomUUID(),reason:'Synthetic register'});
 const write=(id,action,revision,data)=>savePaReport(env,user,{operation:'email_followup',subject_key:id,action,revision,data,request_id:crypto.randomUUID(),reason:'Synthetic evidence'});
 const thread_id='ffee332211',parent_id='abcd0123';
 for(const [i,key] of ids.entries()){
  const data={envelope:{from:'a@example.com',to:['law@example.com'],subject:'Case',body:'Confirm item '+i,scope:'Check item '+i,thread_id,parent_id},review_date:today(),next_action:'Gaan die antwoord na.'};
  await write(key,'draft',0,data);await write(key,'submit',1);
  const m=await readMail(db,key),subject=(await readPaReport(env,user,{resource:'summary',id:key})).subject;
  const ask={action:'respond',request_id:crypto.randomUUID(),subject_key:key,subject_hash:subject.subject_hash,note:'Skryf die opvolg.'};
  assert.equal((await call('alex','/api/pa-report/feedback',ask)).status,200);
  const a={kind:'instruction',text:m.approval_preview,recommendation:'Lees die konsep.',next_action:subject.next_action,responsible:'alex',follow_up_date:subject.review_date,task_status:subject.status};
  await savePaReport(env,user,{operation:'answer',request_id:crypto.randomUUID(),reason:'Synthetic draft reply',feedback_id:ask.request_id,subject_hash:subject.subject_hash,current_subject_hash:subject.subject_hash,revision:1,source_url:url,answer:a});
  const reply={...ask,request_id:crypto.randomUUID(),reply_to:ask.request_id,note:'Dis reg, stuur email.'};
  assert.equal((await call('alex','/api/pa-report/feedback',reply)).status,200);
  await assert.rejects(write(key,'adopt',2,{approval_feedback_id:ask.request_id,proposal_feedback_id:reply.request_id}),/stuurinstruksie/);
  await write(key,'adopt',2,{approval_feedback_id:reply.request_id,proposal_feedback_id:ask.request_id});
  await write(key,'claim',3,{envelope_hash:m.envelope_hash});
  const live=await readMail(db,key);
  await write(key,'bind_draft',4,{claim_id:live.claim_id,draft_id:'r123456'+i});
  await write(key,'sent',5,{...data,evidence:{message_id:'deed000'+i,rfc_id:'<item'+i+'@example.com>',thread_id,labels:['SENT'],envelope_hash:m.envelope_hash,sent_at:new Date().toISOString()}});
 }
 const answer={review_date:today(),next_action:'Kontroleer die dokument.',evidence:{from:'law@example.com',thread_id,message_id:'cafe0022',in_reply_to:'<item1@example.com>',received_at:new Date().toISOString()}};
 await assert.rejects(write(ids[0],'reply',6,answer),/spesifieke/);
 await write(ids[1],'reply',6,answer);
 assert.equal((await readMail(db,ids[0])).phase,'sent');
 assert.equal((await readMail(db,ids[1])).phase,'reply');
});
